-- Schemas, tables and views (idempotent). Run by scripts/deploy.py as ALPHA_APP_READER.
CREATE SCHEMA IF NOT EXISTS PIPEDRIVE.SYNC;
CREATE SCHEMA IF NOT EXISTS PIPEDRIVE.RAW COMMENT = 'Pipedrive extracts, fully refreshed by SYNC_PIPEDRIVE()';
CREATE SCHEMA IF NOT EXISTS PIPEDRIVE.ANALYTICS COMMENT = 'Typed views over RAW';
CREATE SCHEMA IF NOT EXISTS PIPEDRIVE.APP COMMENT = 'Dashboard inputs (targets, FX overrides) and the Streamlit app';

CREATE TABLE IF NOT EXISTS PIPEDRIVE.SYNC.SYNC_LOG (
  STARTED_AT TIMESTAMP_TZ, FINISHED_AT TIMESTAMP_TZ, STATUS STRING, DETAIL STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.APP.REVENUE_TARGETS (
  MONTH_START DATE NOT NULL, TARGET NUMBER(18, 2) NOT NULL,
  UPDATED_BY STRING, UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS PIPEDRIVE.APP.FX_OVERRIDES (
  CURRENCY STRING NOT NULL, RATE_TO_BASE FLOAT NOT NULL,
  UPDATED_BY STRING, UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP());

-- Placeholders so the views compile before the first sync (replaced by SWAP on sync).
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.DEALS (
  ID NUMBER, TITLE STRING, STATUS STRING, PIPELINE_ID NUMBER, STAGE_ID NUMBER, VALUE FLOAT,
  CURRENCY STRING, WEIGHTED_VALUE FLOAT, PROBABILITY FLOAT, EXPECTED_CLOSE_DATE STRING,
  ADD_TIME STRING, UPDATE_TIME STRING, STAGE_CHANGE_TIME STRING, WON_TIME STRING,
  LOST_TIME STRING, CLOSE_TIME STRING, LOCAL_WON_DATE STRING, LOCAL_LOST_DATE STRING,
  LOCAL_CLOSE_DATE STRING, LOST_REASON STRING, ORIGIN STRING, CHANNEL STRING,
  PRODUCTS_COUNT NUMBER, NEXT_ACTIVITY_DATE STRING, LAST_ACTIVITY_DATE STRING,
  VISIBLE_TO STRING, IS_ARCHIVED BOOLEAN, OWNER_ID NUMBER, OWNER_NAME STRING, ORG_ID NUMBER,
  ORG_NAME STRING, PERSON_NAME STRING, LABELS STRING, CUSTOM_FIELDS STRING, RAW STRING,
  LOADED_AT STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.STAGES (
  STAGE_ID NUMBER, PIPELINE_ID NUMBER, ORDER_NR NUMBER, STAGE_NAME STRING,
  DEAL_PROBABILITY FLOAT, ACTIVE BOOLEAN, LOADED_AT STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.PIPELINES (
  PIPELINE_ID NUMBER, PIPELINE_NAME STRING, ORDER_NR NUMBER, ACTIVE BOOLEAN, LOADED_AT STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.USERS (
  USER_ID NUMBER, USER_NAME STRING, EMAIL STRING, ACTIVE BOOLEAN, LOADED_AT STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.DEAL_FIELDS (
  FIELD_KEY STRING, FIELD_NAME STRING, FIELD_TYPE STRING, IS_CUSTOM BOOLEAN, OPTIONS STRING,
  LOADED_AT STRING);
CREATE TABLE IF NOT EXISTS PIPEDRIVE.RAW.FX_RATES (
  CURRENCY STRING, BASE_CURRENCY STRING, RATE_TO_BASE FLOAT, LOADED_AT STRING);

-- One typed row per deal, values converted to the company currency (GBP).
CREATE OR REPLACE VIEW PIPEDRIVE.ANALYTICS.DEALS AS
WITH fx AS (
  SELECT r.CURRENCY, COALESCE(o.RATE_TO_BASE, r.RATE_TO_BASE) AS RATE
  FROM PIPEDRIVE.RAW.FX_RATES r LEFT JOIN PIPEDRIVE.APP.FX_OVERRIDES o USING (CURRENCY)
)
SELECT
  d.ID::NUMBER AS DEAL_ID, d.TITLE, INITCAP(d.STATUS) AS STATUS,
  p.PIPELINE_NAME, s.STAGE_NAME, s.DEAL_PROBABILITY AS STAGE_PROBABILITY,
  CASE d.STATUS WHEN 'won' THEN 100 WHEN 'lost' THEN 0
       ELSE COALESCE(d.PROBABILITY, s.DEAL_PROBABILITY) END AS PROBABILITY,
  d.OWNER_NAME, d.ORG_NAME, d.PERSON_NAME,
  d.VALUE::FLOAT AS VALUE, d.CURRENCY, fx.RATE AS FX_RATE,
  d.VALUE * fx.RATE AS VALUE_GBP,
  d.VALUE * fx.RATE * CASE d.STATUS WHEN 'won' THEN 100 WHEN 'lost' THEN 0
       ELSE COALESCE(d.PROBABILITY, s.DEAL_PROBABILITY) END / 100 AS WEIGHTED_VALUE_GBP,
  TRY_TO_DATE(d.EXPECTED_CLOSE_DATE) AS EXPECTED_CLOSE_DATE,
  TRY_TO_DATE(COALESCE(d.LOCAL_WON_DATE, LEFT(d.WON_TIME, 10))) AS WON_DATE,
  TRY_TO_DATE(COALESCE(d.LOCAL_LOST_DATE, LEFT(d.LOST_TIME, 10))) AS LOST_DATE,
  TRY_TO_TIMESTAMP_NTZ(d.ADD_TIME) AS ADDED_AT_UTC,
  TRY_TO_TIMESTAMP_NTZ(d.UPDATE_TIME) AS UPDATED_AT_UTC,
  PARSE_JSON(d.CUSTOM_FIELDS):"Client Region"::STRING AS CLIENT_REGION,
  PARSE_JSON(d.CUSTOM_FIELDS):"Deal Delivery Region"::STRING AS DEAL_DELIVERY_REGION,
  PARSE_JSON(d.CUSTOM_FIELDS):"Priority Focus"::STRING AS PRIORITY_FOCUS,
  ARRAY_TO_STRING(PARSE_JSON(d.LABELS), ', ') AS SERVICE_LINES,
  d.LOST_REASON, d.ORIGIN,
  PARSE_JSON(d.CUSTOM_FIELDS) AS CUSTOM_FIELDS,
  'https://strata.pipedrive.com/deal/' || d.ID AS PIPEDRIVE_URL,
  d.LOADED_AT
FROM PIPEDRIVE.RAW.DEALS d
LEFT JOIN PIPEDRIVE.RAW.STAGES s ON s.STAGE_ID = d.STAGE_ID
LEFT JOIN PIPEDRIVE.RAW.PIPELINES p ON p.PIPELINE_ID = d.PIPELINE_ID
LEFT JOIN fx ON fx.CURRENCY = d.CURRENCY;
