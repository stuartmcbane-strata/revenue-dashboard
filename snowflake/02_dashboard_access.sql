-- Dashboard access via the Entra ID group AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD.
-- Run once as ACCOUNTADMIN. Entra SCIM provisioning turns the group into a Snowflake role of the
-- same name and creates/disables its members as SSO users.
USE ROLE ACCOUNTADMIN;

-- 1. SCIM provisioning from Entra (skip if Entra already provisions this account).
CREATE ROLE IF NOT EXISTS AAD_PROVISIONER;
GRANT CREATE USER ON ACCOUNT TO ROLE AAD_PROVISIONER;
GRANT CREATE ROLE ON ACCOUNT TO ROLE AAD_PROVISIONER;
GRANT ROLE AAD_PROVISIONER TO ROLE ACCOUNTADMIN;
CREATE SECURITY INTEGRATION IF NOT EXISTS AAD_PROVISIONING
  TYPE = SCIM SCIM_CLIENT = 'AZURE' RUN_AS_ROLE = 'AAD_PROVISIONER';
-- Paste this token into the Snowflake enterprise app > Provisioning > Secret Token
-- (Tenant URL: https://vekqyjp-we74704.snowflakecomputing.com/scim/v2/).
SELECT SYSTEM$GENERATE_SCIM_ACCESS_TOKEN('AAD_PROVISIONING');

-- 2. After the first provisioning cycle has created role "AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD":
--    let the app owner manage the dashboard grants (scripts/deploy.py re-applies them).
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE "AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD";
GRANT USAGE ON DATABASE PIPEDRIVE TO ROLE "AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD";
GRANT USAGE ON SCHEMA PIPEDRIVE.APP TO ROLE "AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD";
GRANT USAGE ON STREAMLIT PIPEDRIVE.APP.PIPEDRIVE_REVENUE_DASHBOARD TO ROLE "AAD-SNOWFLAKE_PIPEDRIVE_DASHBOARD";
